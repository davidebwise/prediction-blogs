// On par with UEFA's weakest members / outside UEFA entirely.
const UNKNOWN_UEFA_COEFFICIENT = 5;

function getCountryRating(countryName, isNationalTeam) {
  if (!countryName) return null;
  return isNationalTeam ? FIFA_RANKING[countryName] ?? null : UEFA_COEFFICIENTS[countryName] ?? null;
}

// Higher is always stronger, regardless of which table was used.
// - National teams: 1/sqrt(rank), since rank 1 is best.
// - Clubs: sqrt(coefficient), since a higher coefficient is best; sqrt compresses the raw
//   range (2.5 to 115) so it meaningfully nudges the position-based comparison without
//   completely overwhelming it.
function getCountryStrengthFactor(countryName, isNationalTeam) {
  if (isNationalTeam) {
    const rank = getCountryRating(countryName, true) ?? UNKNOWN_FIFA_RANK;
    return 1 / Math.sqrt(rank);
  }
  const coefficient = getCountryRating(countryName, false) ?? UNKNOWN_UEFA_COEFFICIENT;
  return Math.sqrt(coefficient);
}

